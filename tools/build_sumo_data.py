"""Build sumo/data.js from sumo/bank.txt + data/dict.js.

Usage: python3 tools/build_sumo_data.py
Validates the clue bank (answers must be dictionary words with readings, and a
description may not contain any kanji of its answer), then writes a compact
data file with clues, readings, meanings, homophones and a word list.
"""
import json, os, re, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KANJI = re.compile(r'[一-鿿]')
# Readings the dictionary gets wrong for our intended sense.
READING_FIX = {'金星': 'きんぼし'}

def load_dict():
    s = open(os.path.join(ROOT, 'data', 'dict.js'), encoding='utf-8').read()
    s = s[s.index('{'):s.rindex('}') + 1]
    return json.loads(s)

def main():
    d = load_dict()
    w2 = d['d']['w2']
    common = {w2[i:i + 2] for i in range(0, len(w2), 2)} | set(d['d']['wL'])
    words = common | set(d['rare'])
    lex, rlex = d['lex'], d['rlex']
    by_reading = defaultdict(set)
    for w, v in lex.items():
        if v and v[0]: by_reading[v[0]].add(w)

    topics, errors, cur = [], [], None
    for n, line in enumerate(open(os.path.join(ROOT, 'sumo', 'bank.txt'), encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'): continue
        if line.startswith('@'):
            key, label, icon = line[1:].split('|')
            cur = {'key': key, 'label': label, 'icon': icon, 'e': []}
            topics.append(cur); continue
        ans, desc, alts = (line.split('|') + [''])[:3]
        alts = [a for a in alts.split(',') if a]
        for w in [ans] + alts:
            if w not in words and w not in lex and w not in rlex:
                errors.append(f'{n}: {w} not in dictionary')
        lx = lex.get(ans) or rlex.get(ans)
        reading = READING_FIX.get(ans) or (lx[0] if lx else '')
        if not reading: errors.append(f'{n}: no reading for {ans}')
        leak = [c for c in ans if c in desc]
        if leak: errors.append(f'{n}: description of {ans} leaks {"".join(leak)}')
        homo = sorted(w for w in by_reading.get(reading, ()) if w != ans and w not in alts and w in common)
        cur['e'].append([ans, reading, desc, alts, (lx[1] if lx else ''), homo[:6]])

    if errors:
        print('\n'.join(errors)); sys.exit(1)
    out = {'topics': topics, 'w2': w2, 'wL': d['d']['wL']}
    js = '// Generated by tools/build_sumo_data.py — edit sumo/bank.txt instead.\n' \
         '// entry: [answer, reading, description, alts, english, homophones]\n' \
         'window.KZ_DATA=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
    open(os.path.join(ROOT, 'sumo', 'data.js'), 'w', encoding='utf-8').write(js)
    print(f'{len(topics)} topics, {sum(len(t["e"]) for t in topics)} entries, {len(js)//1024} KB')

if __name__ == '__main__':
    main()
